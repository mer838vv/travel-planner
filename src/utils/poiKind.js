/**
 * Тип точки маршрута.
 *
 * Раньше все точки дня выглядели одинаково: вылет, заселение в отель и
 * прогулка по площади рисовались одной и той же карточкой. Это ломает
 * иерархию — логистику нельзя пропустить, а достопримечательность можно,
 * и глаз должен различать их до чтения текста.
 *
 * Тип задаёт агент полем `kind`. Для точек, добавленных руками, он
 * угадывается по названию — не идеально, но лучше, чем сплошная серость.
 */

export const KINDS = {
  flight: { icon: '✈️', label: 'Перелёт', tone: 'blue' },
  transfer: { icon: '🚕', label: 'Дорога', tone: 'orange' },
  hotel: { icon: '🏨', label: 'Жильё', tone: 'violet' },
  food: { icon: '🍽️', label: 'Еда', tone: 'green' },
  sight: { icon: '🏛️', label: 'Место', tone: 'teal' },
  nature: { icon: '🌿', label: 'Природа', tone: 'green' },
  shop: { icon: '🛍️', label: 'Покупки', tone: 'pink' },
  other: { icon: '📍', label: '', tone: 'grey' },
}

// Логистика — то, что нельзя пропустить: выделяется сильнее остального.
const LOGISTICS = new Set(['flight', 'transfer', 'hotel'])

export function isLogistics(kind) {
  return LOGISTICS.has(kind)
}

/**
 * Ключевые слова ищутся только с начала слова.
 *
 * `\b` в JavaScript опирается на латиницу и с кириллицей не работает, а без
 * границы «сад» находился внутри «пере-САД-ка», и пересадка в Стамбуле
 * распознавалась как парк. Поэтому перед словом требуется начало строки или
 * не-буква; окончание свободное, чтобы «сад» ловил и «сады», «саду».
 */
function stems(...words) {
  return new RegExp(`(?:^|[^\\p{L}])(?:${words.join('|')})`, 'iu')
}

const PATTERNS = [
  [stems('аэропорт', 'airport', 'вылет', 'прилёт', 'прилет', 'рейс', 'терминал',
         'пересадк', 'фьюмичино', 'шереметьево', 'стыковк'), 'flight'],
  // «Вилла» намеренно не здесь: вилла Боргезе — парк, а не жильё. Снятую
  // виллу агент помечает явным `kind`, и ошибка в другую сторону дороже.
  [stems('отель', 'hotel', 'заселени', 'выселени', 'check', 'апартамент',
         'хостел', 'гостиниц', 'inn', 'resort'), 'hotel'],
  [stems('вокзал', 'станци', 'поезд', 'автобус', 'такси', 'трансфер', 'выезд',
         'паром', 'прокат', 'аренда авто'), 'transfer'],
  [stems('ресторан', 'кафе', 'обед', 'ужин', 'завтрак', 'бар', 'траттори',
         'остери', 'пекарн', 'рынок', 'дегустац', 'винодельн', 'ферма'), 'food'],
  [stems('парк', 'сад', 'пляж', 'озеро', 'гора', 'водопад', 'заповедник',
         'тропа', 'набережн'), 'nature'],
  [stems('магазин', 'шопинг', 'бутик', 'аутлет', 'торгов'), 'shop'],
  [stems('музе', 'собор', 'базилик', 'храм', 'церк', 'замок', 'дворец',
         'галере', 'площад', 'фонтан', 'колизей', 'форум', 'руин',
         'крепост', 'мост', 'башн', 'вилл'), 'sight'],
]

function matchKind(text) {
  for (const [pattern, kind] of PATTERNS) {
    if (pattern.test(text)) return kind
  }
  return null
}

/**
 * Тип точки: явно заданный, иначе угаданный.
 *
 * Название проверяется отдельно и первым: в описании отеля почти наверняка
 * упомянут аэропорт или трансфер, и общий поиск по name+description
 * превращал «Hilton Garden Inn» в перелёт. Описание — только запасной
 * источник, когда по названию ничего не понятно.
 */
export function resolveKind(poi) {
  if (poi?.kind && KINDS[poi.kind]) return poi.kind

  return matchKind(poi?.name || '')
    || matchKind(poi?.description || '')
    || 'other'
}

export function kindMeta(kind) {
  return KINDS[kind] || KINDS.other
}
